    boolean pixel(int x, int y) {
        return x >= 0 && x < 16 && y >= 0 && y < 16 && (rows[y] & (1 << (15 - x))) != 0;
    }

    private static short[] rows(String... values) {
        if (values.length != 16) throw new IllegalArgumentException("An icon requires 16 rows");
        short[] result = new short[16];
        for (int y = 0; y < values.length; y++) {
            if (values[y].length() != 16) throw new IllegalArgumentException("An icon row requires 16 pixels");
            int bits = 0;
            for (int x = 0; x < 16; x++) {
                if (values[y].charAt(x) == '#') bits |= 1 << (15 - x);
            }
            result[y] = (short) bits;
        }
        return result;
    }
